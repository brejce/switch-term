-- v2 分体键盘：每手 5 列 × 4 行 = 20 键，共 40。行列照真实 108 键盘组织（docs/KEYMAP-108.md）。
-- 坐标是**局部坐标**：世界比面板大，左右手各是一个独立的 5×4 场，两面共用这一套坐标；
-- 屏上位置由渲染算：offset = 面板中心 - 摄像机。
-- 键序 = 左手 row-major(4×5) 再接右手 row-major(4×5)
ui.key_size = 48    -- 键帽边长；字符字号见 screen.cpp 的 drawKeyHand（26/12，随它缩放）

-- 面板一屏露几列几行（滑窗可见范围）：3 列 = 2×58+48 = 164，塞进 panel_w 176。
-- 3 行 = 2×62+48 = 172，正好等于遮罩半径 kMaskOut（遮罩外本来就看不见）。
-- 4 行 = 整个 4 行世界一次全露（数字行常驻可见），纵向因此不滚、画布不会露白；
-- 横向世界 5 列只露 3 列 → 余 2 列（±58）可滚。看不见的键交给径向遮罩压成半透明。
ui.key_window = { cols = 3, rows = 4 }

-- 键区整体纵向偏移（设计像素，负 = 上移）：把键区往上挪，下面留白给按钮簇/状态
ui.key_area_dy = -100   -- 上移量（负=上移）；顶部要留肩键提示、下面要留按钮簇

local function hand_keys()
    local t = {}
    for r = 0, 3 do
        for c = 0, 4 do
            t[#t + 1] = {x = c * 58, y = r * 62}  -- 键 48，横向间隙 10、纵向间隙 14
        end
    end
    return t
end

ui.keys = {}  -- 左手 20 个再右手 20 个，坐标相同（两场互不干扰）
for _, side in ipairs({hand_keys(), hand_keys()}) do
    for _, k in ipairs(side) do
        ui.keys[#ui.keys + 1] = k
    end
end

