-- 引擎装配：这里只放「看不见」的参数（终端/输入法/输入设备/日志/输出口）。
-- 看得见的东西（尺寸/键表/标签/字体/主题）在 ui.lua 和 keymap.lua，两类文件分开改。
-- C++ 只读这张表；缺键 = 用 src/config/lua_config.h 里 Engine 的默认值。

engine = {}

engine.terminal = {
    scrollback = 2000,   -- 终端向上保留多少行历史（--legacy 的滚动回放也读它）
}

engine.ime = {
    cand_per_page = 7,   -- 底部候选条一页显示几个（IME 内部翻页跨度也跟着变）
    ngram         = true, -- 候选要不要用 bigram 上下文重排（目前只解析，未接线）
    enabled       = true, -- false = 内置输入法不介入，字符原样透传（桌面模式与 fcitx 共存）
}

engine.input = {
    deadzone       = 0.1,  -- 摇杆死区：半径 10 里的内圈 1（回中漂移全落这里，滤成 0）。
                           -- 太小 = 松手还当推着，永远回不了零位；太大 = 前段行程白推
    hysteresis_deg = 8,    -- 扇区切换滞回角：防止在边界上来回抖出字母
    double_tap_ms  = 400,  -- 同一个键在这个时间内按第二下 = 双击（十字键锁定修饰）
}

engine.log = {
    level = "warn",      -- 日志级别：debug | info | warn | error（目前只打印，未接线）
    path  = "",          -- 日志文件路径，空 = 只写 stderr
}

-- 屏幕方向：这是平台属性（面板怎么装的），不属于布局，所以不放 ui.lua
engine.display = {
    rotate = 270,         -- 0 | 90 | 180 | 270（顺时针）；只对 fbdev 生效，SDL 忽略
}

engine.sink = "pty"       -- 输出口：pty = 写自带伪终端；uinput = 当虚拟键盘打给系统（需 /dev/uinput 可写，打不开自动回落 pty）

-- 物理（引力选键，docs/PHYSICS.md）：两个摇杆各驱动一个粒子，在各自 15 键的引力场里飞。
-- 手感旋钮，改这里就能调；dt 不在这里（C++ 里写死 1/60，保证同一输入序列可回放）。
engine.physics = {
    damping        = 0.26, -- 惯性衰减：每帧向目标速度收敛 (1-它)。0.35 → 0.26 = 同速所需时间 ÷1.3（加速度快 30%）
    attract_power  = 117,  -- 引力强度（每帧直接加多少 px/s）：90 × 1.3 = 117，一靠近就被“拽”进键心，吸附感明显。
                           -- 1 = 等于没磁力（旧的 40px 键距时留下的值）；键心 6px 内引力会淡出，
                           -- 所以 100~400 也不会抖（800 起才有 1px 残留摆动），只有"拖不走"的代价
    attract_radius = 76,   -- 引力作用半径（px）：正好够到邻键中心，一推就点亮下一键（和键窗动效用同一个值）
    snap_radius    = 32,   -- 吸附半径（px）：键 64 → 键面（内切圆半径 32）内就吸，靠近键帽就“咔”地选中；
                           -- 两键之间只留 10px 行程（原来 22 留 26px，导致亮了还要微调才变白）
    release_ratio  = 1.3,  -- 脱开距离 = snap_radius × 它 ≈ 42px（键距放大后同比放大，黏性不变）
    release_power  = 0.35, -- 已废弃（保留只为旧配置不报错）：它与引力打架导致吸附键闪烁，
                           -- 现在脱开判据只有 release_ratio 的距离
    max_speed      = 1730, -- px/s，推到底的时速（最快）
    speed_slow_end = 0.5,  -- 内圈微操段到半径 10 的 5 为止（1..5 = 微操，5..10 = 快速）
    speed_low      = 0.15, -- 微操段顶端的速度（× max_speed）：内圈再推也只有这么快。
                           -- 0.15×1600 ≈ 240px/s = 原来 0.3×800，内圈手感不变，只提外围
    speed_power    = 1.6,  -- 外段曲线指数：1 = 线性；>1 = 越靠外斜率越大（边缘最快、不发木）。
                           -- 旧值是 smoothstep，斜率到边缘又归零，所以推到底和八成差不多快
    hover_radius   = 37,   -- 弱高亮半径（px）：只比 snap 大 4px，所以“变亮”基本等于“即将吸附”，不再有长段预告区
    home_pull      = 0.6,  -- 零位回落：松手 0.3s 后按这个比例收回 home（0 = 关，停在哪算哪）
    pointer_radius = 23,   -- 指针球半径（px）：0 = 原点模型。吸附判定 = 球心距 < snap_radius + 它，
                           -- 球边缘碰键才吸，键也更早被点亮（吸附感更干脆）。
                           -- 21 → 直径 42 ≈ 键 64 的 2/3（屏幕上画的那个方框就是这个尺寸）
}

-- 震动（Joy-Con evdev FF，event8 实测支持 FF_RUMBLE）。两个用途分开调：
--   移动底噪：指针在飞的时候持续弱震，像东西在滚；强度跟指针速度走
--   吸附"咚"：吸住一个键时短促一下，像球掉进坑里
engine.rumble = {
    enabled        = true,
    move_max       = 0.30, -- 底噪最大强度（0..1）：再大就糊成一直震、分不出吸附那一下
    move_speed_ref = 500,  -- 指针速度到这么多 px/s 就算推满 → 映射到 move_max
    snap_strong    = 0.55, -- 吸附那一下的强马达（低频"咚"）
    snap_weak      = 0.30, -- 吸附那一下的弱马达（高频"嗒"）
    snap_ms        = 55,   -- 持续时长：太长会和下一颗键的"咚"糊在一起
    rate_hz        = 40,   -- 底噪刷新率上限（每帧发 ioctl 太重）
    move_smooth_ms = 60,   -- 底噪强度的低通时间常数：越小越"颗粒"，越大越绵（不细腻就是这里）
    -- 左右分侧震动：左手柄用 gain_left、右手柄用 gain_right。实测右边马达偏弱，
    -- 所以把左边压一点（不是把右边加大——FF 幅度已经是 0xFFFF，加不上去）
    gain_left      = 0.50,
    gain_right     = 1.00,
}
